#!/usr/bin/env python3
"""Fold a test category into one binary: N full compiles -> 1.

Every `tests/<cat>/test_*.nim` is a unittest module that pays its own Nim
frontend + C compile + link pass. This generates `build/fold_<cat>.nim`
importing each module in the category, compiles that once, and runs the
single binary. Only fold categories proven green as one binary (process
isolation is traded for compile cost); config is: 592 tests, 0 failures,
~113s total versus ~1131s serial.

Usage: fold_category.py [--timeout SECS] [--list] CATEGORY
  --timeout S  run cap for the folded binary (default 720, 0 = off)
  --list       print the modules and exit
"""
import argparse
import os
import subprocess
import sys

ROOT = os.getcwd()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("category")
    ap.add_argument("--timeout", type=int, default=720)
    ap.add_argument("--list", action="store_true")
    args = ap.parse_args()

    cat = args.category.strip("/")
    if not cat or "/" in cat or cat in (".", ".."):
        ap.error("category is a name under tests/, not a path")
    catdir = os.path.join(ROOT, "tests", cat)
    files = sorted(f for f in os.listdir(catdir)
                   if f.startswith("test_") and f.endswith(".nim"))
    if not files:
        print(f"fold_category: no test_*.nim in tests/{cat}", file=sys.stderr)
        return 1
    if args.list:
        for f in files:
            print(f)
        return 0

    src = os.path.join(ROOT, "build", f"fold_{cat}.nim")
    binary = os.path.join(ROOT, "build", f"fold_{cat}")
    if sys.platform.startswith("win"):
        binary += ".exe"
    os.makedirs(os.path.dirname(src), exist_ok=True)
    with open(src, "w", encoding="utf-8") as f:
        f.write("# Generated by tests/tools/fold_category.py; do not edit.\n")
        for mod in files:
            f.write(f"import {cat}/{mod[:-4]}\n")

    cmd = ["nim", "c", "--hints:on", "-d:testing",
           "--nimblePath:build/deps/pkgs2", "--path:src", "--path:tests",
           "--nimcache:" + os.path.join(ROOT, "build", f"fold_{cat}_cache"),
           "--out:" + binary, src]
    print(f"fold_category: {len(files)} modules -> one binary", flush=True)
    if subprocess.call(cmd, cwd=ROOT) != 0:
        return 1
    try:
        return subprocess.call(
            [binary], cwd=ROOT,
            timeout=args.timeout if args.timeout > 0 else None)
    except subprocess.TimeoutExpired:
        print(f"fold_category: {cat} timed out after {args.timeout}s",
              file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
