## Computer use, X11 backend. Two pieces:
##
## - capture: `captureScreenshot` grabs the root window via the first of
##   import/maim/scrot that actually works, re-encodes through the shared
##   vision budget encoder, and writes the frame state (native vs delivered
##   geometry) next to the generated `shot` script. Runs in this process,
##   outside the wall proxy that fences bash children — same standing
##   exemption web_fetch has. A capture must reach the real X server.
## - the `shot` companion: a self-contained POSIX sh script (kept in
##   `ShotScriptText`) the model drives through the ordinary bash tool.
##   It takes delivered-raster coordinates and owns the native mapping via
##   the state file, so the model never does scale math. Stale state (no
##   capture yet, or the screen resolution changed) is a loud error telling
##   the model to call `screenshot()` first.
##
## The script and its state live under the temp dir, not the session dir:
## the bash child's sandbox policy always leaves the temp dir readable
## (its own command script runs from there), while the session dir is not
## necessarily readable, and the frame state is per-run ephemeral anyway —
## a resumed session takes a fresh screenshot before acting.

import std/[os, osproc, sequtils, strformat, strutils]
import images

const
  ShotScriptName = "shot"
  ShotStateName = "state"
  CaptureTools = ["import", "maim", "scrot"]

const ShotScriptText = """#!/bin/sh
# shot — drive the desktop with delivered-raster coordinates.
# Generated by 3code. Coordinates are pixels in the LAST raster the
# screenshot() tool delivered; this script maps them to the native screen.
# A missing state file or a resolution change means the frame is stale:
# call screenshot() and act on the fresh image.
set -u
STATE="$(dirname "$0")/state"
die() { echo "shot: $*" >&2; exit 1; }
command -v xdotool >/dev/null 2>&1 || die "xdotool not found — install xdotool"
[ -f "$STATE" ] || die "stale frame: no screenshot state — call screenshot() first"
NW=$(sed -n 's/^native=\([0-9]*\)x[0-9]*$/\1/p' "$STATE")
NH=$(sed -n 's/^native=[0-9]*x\([0-9]*\)$/\1/p' "$STATE")
DW=$(sed -n 's/^delivered=\([0-9]*\)x[0-9]*$/\1/p' "$STATE")
DH=$(sed -n 's/^delivered=[0-9]*x\([0-9]*\)$/\1/p' "$STATE")
[ -n "$NW" ] && [ -n "$NH" ] && [ -n "$DW" ] && [ -n "$DH" ] || \
  die "corrupt state file — call screenshot() again"
CUR=$(xdotool getdisplaygeometry) || die "cannot reach the X display (DISPLAY=${DISPLAY:-unset})"
CURW=${CUR% *}; CURH=${CUR#* }
[ "$CURW" = "$NW" ] && [ "$CURH" = "$NH" ] || \
  die "stale frame: screen is ${CURW}x${CURH}, captured frame was ${NW}x${NH} — call screenshot() again"
map() {
  awk -v x="$1" -v y="$2" -v nw="$NW" -v nh="$NH" -v dw="$DW" -v dh="$DH" 'BEGIN {
    nx = int((x + 0.5) * nw / dw); ny = int((y + 0.5) * nh / dh)
    if (nx > nw - 1) nx = nw - 1
    if (ny > nh - 1) ny = nh - 1
    printf "%d %d", nx, ny }'
}
cmd="${1:-}"
[ -n "$cmd" ] || die "usage: shot click|doubleclick|rightclick|middleclick X Y | drag X1 Y1 X2 Y2 | type TEXT | key KEYS | scroll up|down N | title"
shift
case "$cmd" in
  click)
    [ $# -ge 2 ] || die "usage: shot click X Y"
    set -- $(map "$1" "$2")
    xdotool mousemove "$1" "$2" click 1 ;;
  doubleclick)
    [ $# -ge 2 ] || die "usage: shot doubleclick X Y"
    set -- $(map "$1" "$2")
    xdotool mousemove "$1" "$2" click --repeat 2 --delay 120 1 ;;
  rightclick)
    [ $# -ge 2 ] || die "usage: shot rightclick X Y"
    set -- $(map "$1" "$2")
    xdotool mousemove "$1" "$2" click 3 ;;
  middleclick)
    [ $# -ge 2 ] || die "usage: shot middleclick X Y"
    set -- $(map "$1" "$2")
    xdotool mousemove "$1" "$2" click 2 ;;
  drag)
    [ $# -ge 4 ] || die "usage: shot drag X1 Y1 X2 Y2"
    set -- $(map "$1" "$2") $(map "$3" "$4")
    xdotool mousemove "$1" "$2" mousedown 1 mousemove --sync "$3" "$4" mouseup 1 ;;
  type)
    [ $# -ge 1 ] || die "usage: shot type TEXT"
    xdotool type -- "$*" ;;
  key)
    [ $# -ge 1 ] || die "usage: shot key KEYS (e.g. ctrl+s, alt+Tab)"
    xdotool key "$@" ;;
  scroll)
    [ $# -ge 2 ] || die "usage: shot scroll up|down N"
    case "$1" in up|down) ;; *) die "usage: shot scroll up|down N" ;; esac
    [ "$2" -ge 1 ] 2>/dev/null || die "scroll count must be a positive number"
    BTN=4
    [ "$1" = "down" ] && BTN=5
    xdotool click --repeat "$2" "$BTN" ;;
  title)
    NAME=$(xdotool getactivewindow getwindowname 2>/dev/null || echo "?")
    SCALE=$(awk -v nw="$NW" -v dw="$DW" 'BEGIN { printf "%.3f", nw / dw }')
    echo "window: $NAME"
    echo "native: ${NW}x${NH}  delivered: ${DW}x${DH}  scale: $SCALE" ;;
  *)
    die "unknown subcommand: $cmd (click doubleclick rightclick middleclick drag type key scroll title)" ;;
esac
"""

var shotHomeDir*: string
  ## Where the generated `shot` script and its state file live. Empty
  ## until `ensureComputerUse` succeeds; `screenBackendOk` is the offer
  ## gate for the screenshot tool schema.

proc screenBackendOk*(): bool = shotHomeDir.len > 0

proc shotDir*(sessionId: string): string =
  getTempDir() / ("3code-shot-" & (if sessionId.len > 0: sessionId else: "default"))

proc shotScriptPath*(sessionId: string): string =
  shotDir(sessionId) / ShotScriptName

proc platformNotSupportedError(): string =
  ## Phase-3 platform table: X11 is the only implemented backend; the
  ## others must fail loudly rather than half-work. The OS arms are
  ## compile-time; Wayland detection is runtime env (a `when` there would
  ## fold against the *compiler's* environment, not the user's session).
  when defined(macosx):
    "error: computer use: the macOS backend (screencapture + cliclick) is " &
      "not implemented yet — X11 only for now"
  elif defined(windows):
    "error: computer use: the Windows backend (.NET SendInput) is not " &
      "implemented yet — X11 only for now"
  else:
    if getEnv("WAYLAND_DISPLAY").len > 0 and getEnv("DISPLAY").len == 0:
      "error: computer use: Wayland is not supported here yet (grim + " &
        "ydotool backend unimplemented) — run under X11 (Xwayland counts)"
    else:
      ""

proc materializeShotScript*(dir: string): string =
  ## Write (or refresh) `dir/shot`. Empty return = ok. Split out of
  ## `ensureComputerUse` so tests can generate the script without an X
  ## server — the script's logic only needs sh + awk + a stubbed xdotool.
  try:
    createDir(dir)
    let script = dir / ShotScriptName
    writeFile(script, ShotScriptText)
    setFilePermissions(script,
      {fpUserRead, fpUserWrite, fpUserExec,
       fpGroupRead, fpGroupExec, fpOthersRead, fpOthersExec})
    ""
  except CatchableError as e:
    &"error: computer use: cannot write {dir}: {e.msg}"

proc ensureComputerUse*(sessionId: string): tuple[ok: bool, err: string] =
  ## Probe the backend and materialize the `shot` script. Idempotent;
  ## plain string errors, no exceptions. The capture tool is probed by
  ## existence only — a present-but-broken `import` falls through to the
  ## next tool at capture time (first success wins).
  let platformErr = platformNotSupportedError()
  if platformErr.len > 0:
    return (false, platformErr)
  if getEnv("DISPLAY").len == 0:
    return (false, "error: computer use: no DISPLAY — needs an X11 session")
  if findExe("xdotool").len == 0:
    return (false, "error: computer use: xdotool not found — install " &
      "xdotool (actions) and one of scrot/maim/imagemagick (capture)")
  if not CaptureTools.anyIt(findExe(it).len > 0):
    return (false, "error: computer use: no screen capture tool found — " &
      "install scrot, maim or imagemagick (import)")
  let dir = shotDir(sessionId)
  let err = materializeShotScript(dir)
  if err.len > 0:
    return (false, err)
  shotHomeDir = dir
  (true, "")

proc writeShotState(info: ImageInfo): string =
  ## Frame binding for `shot`: the delivered raster's geometry plus the
  ## native screen it was captured from. Empty return = ok.
  try:
    writeFile(shotHomeDir / ShotStateName,
      &"native={info.width}x{info.height}\n" &
      &"delivered={info.deliveredWidth}x{info.deliveredHeight}\n")
    ""
  except CatchableError as e:
    "error: screenshot: cannot write shot state: " & e.msg

proc captureScreenshot*(destDir: string,
    fidelity = false): tuple[info: ImageInfo, err: string] =
  ## Capture the root window and encode it into `destDir` under the shared
  ## vision budget. The returned ImageInfo has `screenshot` set and
  ## `name` = `shot N` (N = the delivered file index). Errors are plain
  ## strings. `THREECODE_SCREENSHOT_SRC` overrides the capture binaries
  ## with a fixed image file — the test seam (also a recovery hatch for
  ## headless runs).
  var src = getEnv("THREECODE_SCREENSHOT_SRC")
  if src.len > 0:
    if not fileExists(src):
      return (ImageInfo(), &"error: screenshot: {src} does not exist")
  else:
    if getEnv("DISPLAY").len == 0:
      return (ImageInfo(),
        "error: screenshot: no DISPLAY — computer use needs an X11 session")
    let tmp = getTempDir() / "3code-screen.png"
    var tried: seq[string]
    var lastOutp = ""
    for exe in CaptureTools:
      if findExe(exe).len == 0: continue
      tried.add exe
      try: removeFile(tmp)
      except CatchableError: discard
      let args = case exe
        of "import": @[exe, "-window", "root", tmp]
        else: @[exe, tmp]
      let (outp, code) = execCmdEx(args.map(quoteShell).join(" "))
      if code == 0 and fileExists(tmp) and getFileSize(tmp) > 0:
        src = tmp
        break
      lastOutp = outp.strip
    if src.len == 0:
      if tried.len == 0:
        return (ImageInfo(), "error: screenshot: no capture tool found " &
          "(install scrot, maim or imagemagick)")
      let why = if lastOutp.len > 0:
        ": " & lastOutp[0 ..< min(200, lastOutp.len)] else: ""
      return (ImageInfo(), "error: screenshot: capture failed (tried " &
        tried.join(", ") & ")" & why & " — is the X server reachable?")
  let idx = nextImageIndex(destDir)
  let (info, encErr) = encodeForVision(src, destDir, idx, fidelity)
  if encErr.len > 0:
    return (ImageInfo(), encErr)
  var res = info
  res.name = &"shot {idx}"
  res.screenshot = true
  if shotHomeDir.len > 0:
    let stErr = writeShotState(res)
    if stErr.len > 0:
      return (ImageInfo(), stErr)
  (res, "")

func computerUseNote*(shotPath: string): string =
  ## The one-time activation note (dmail pattern: a user message, never a
  ## system-prompt edit). Ports the load-bearing rules: observe->act->
  ## verify, never replay a sent action, coordinate discipline, plus the
  ## `shot` cheat sheet. ~1.5K chars, paid once per session at activation.
  result = "[computer use on] You can now see and drive this desktop.\n" &
    "\n" &
    "screenshot() captures the screen; the image arrives with your next " &
    "message. Coordinates you read off it are pixels of that delivered " &
    "raster (at most 1280 on the long edge), never the native screen.\n" &
    "\n" &
    "The shot script drives mouse and keyboard, taking delivered-raster " &
    "coordinates and doing the mapping itself:\n" &
    "  " & shotPath & " click 640 360    also doubleclick/rightclick/" &
    "middleclick X Y\n" &
    "  " & shotPath & " drag 100 100 400 400\n" &
    "  " & shotPath & " type \"hello world\"    types into the focused " &
    "window\n" &
    "  " & shotPath & " key ctrl+s            also enter, alt+Tab, " &
    "ctrl+shift+t\n" &
    "  " & shotPath & " scroll up 3           or scroll down 5\n" &
    "  " & shotPath & " title                 active window + geometry " &
    "+ scale\n" &
    "Never do the scale math yourself, and never feed screenshot " &
    "coordinates to raw xdotool — always go through shot.\n" &
    "\n" &
    "Working rules:\n" &
    "- Observe, act, verify: screenshot() to see, one shot action, then " &
    "screenshot() again to verify. Act on what you see, not what you " &
    "expect.\n" &
    "- A sent action may already have run. After an interruption or any " &
    "doubt, re-observe before acting again — never replay an action " &
    "blind.\n" &
    "- 'stale frame' from shot means the screen changed since your " &
    "capture: screenshot() again before acting.\n" &
    "- Screenshots show pixels, not correctness; verify real work from " &
    "artifacts (files, exit codes, tests).\n" &
    "- These actions drive the user's real desktop with no sandbox; the " &
    "user sees everything. Esc/Ctrl-C is the panic button. Stop driving " &
    "the desktop when the task no longer needs it."

func screenshotReceipt*(info: ImageInfo): string =
  ## Text receipt for a capture; `screenshotBanner` parses this shape.
  &"screenshot {info.width}x{info.height} -> delivered " &
    &"{info.deliveredWidth}x{info.deliveredHeight} {info.format.toUpperAscii}" &
    "; shot attached below"

func isScreenshotReceipt*(res: string): bool =
  res.startsWith("screenshot ") and "; shot attached below" in res

func screenshotBanner*(receipt: string): string =
  ## One-line transcript form: `screenshot 1920x1080 -> delivered
  ## 1280x720 JPEG; ...` becomes `· shot 1920x1080 -> 1280x720`.
  let semi = receipt.find(';')
  let toks = (if semi > 0: receipt[0 ..< semi] else: receipt).split(' ')
  if toks.len >= 6: &"· shot {toks[1]} -> {toks[4]}" else: receipt
